# ------------------------------------------------------------------ Schrift bauen

def fett(zeilen):
    """Jeder Pixel einen Schritt nach rechts verlängert (wie die fette Spielschrift)."""
    neu = []
    for r in zeilen:
        r2 = list(r + ".")
        for i, c in enumerate(r):
            if c == '#':
                r2[i + 1] = '#'
        neu.append("".join(r2))
    return neu


def glyphe(zeilen, unten):
    pen = TTGlyphPen(None)
    h = len(zeilen)
    for zi, r in enumerate(zeilen):
        y = unten + (h - 1 - zi)
        x = 0
        while x < len(r):
            if r[x] != '#':
                x += 1
                continue
            start = x
            while x < len(r) and r[x] == '#':
                x += 1
            # Rechteck im Uhrzeigersinn (TrueType: außen im Uhrzeigersinn)
            x0, x1, y0, y1 = start * PX, x * PX, y * PX, (y + 1) * PX
            pen.moveTo((x0, y0))
            pen.lineTo((x0, y1))
            pen.lineTo((x1, y1))
            pen.lineTo((x1, y0))
            pen.closePath()
    return pen.glyph()


def name_fuer(ch):
    return "uni%04X" % ord(ch) if ord(ch) <= 0xFFFF else "u%05X" % ord(ch)


def baue(datei, ist_fett):
    fb = FontBuilder(UPM, isTTF=True)
    namen = [".notdef", "space"]
    glyphen = {}
    breiten = {}

    leer = TTGlyphPen(None)
    x0, y0, x1, y1 = 0, 0, 5, 7          # Ersatzzeichen: hohles Kästchen
    for rx0, ry0, rx1, ry1 in [(x0, y0, x1, y0 + 1), (x0, y1 - 1, x1, y1), (x0, y0 + 1, x0 + 1, y1 - 1), (x1 - 1, y0 + 1, x1, y1 - 1)]:
        leer.moveTo((rx0 * PX, ry0 * PX))
        leer.lineTo((rx0 * PX, ry1 * PX))
        leer.lineTo((rx1 * PX, ry1 * PX))
        leer.lineTo((rx1 * PX, ry0 * PX))
        leer.closePath()
    glyphen[".notdef"] = leer.glyph()
    breiten[".notdef"] = (6 * PX, 0)
    glyphen["space"] = TTGlyphPen(None).glyph()
    breiten["space"] = ((5 if ist_fett else 4) * PX, 0)
    cmap = {32: "space", 0xA0: "space"}

    for ch, (zeilen, unten) in sorted(G.items(), key=lambda e: ord(e[0])):
        if ist_fett:
            zeilen = fett(zeilen)
        n = name_fuer(ch)
        namen.append(n)
        glyphen[n] = glyphe(zeilen, unten)
        breiten[n] = ((len(zeilen[0]) + 1) * PX, 0)
        cmap[ord(ch)] = n

    fb.setupGlyphOrder(namen)
    fb.setupCharacterMap(cmap)
    fb.setupGlyf(glyphen)
    fb.setupHorizontalMetrics(breiten)
    fb.setupHorizontalHeader(ascent=ASC * PX, descent=-DESC * PX, lineGap=GAP * PX)
    familie = "Bambus Pixel"
    stil = "Bold" if ist_fett else "Regular"
    fb.setupNameTable({
        "familyName": familie,
        "styleName": stil,
        "uniqueFontIdentifier": familie + " " + stil,
        "fullName": familie + (" Bold" if ist_fett else ""),
        "psName": "BambusPixel-" + stil,
        "version": "Version 1.000",
        "copyright": "Bambus Client – eigene Pixelschrift (MIT-Lizenz)",
    })
    fb.setupOS2(sTypoAscender=ASC * PX, sTypoDescender=-DESC * PX, sTypoLineGap=GAP * PX,
                usWinAscent=ASC * PX, usWinDescent=DESC * PX, sxHeight=5 * PX, sCapHeight=7 * PX,
                usWeightClass=700 if ist_fett else 400, fsSelection=0x20 if ist_fett else 0x40)
    fb.setupPost()
    if ist_fett:
        fb.font["head"].macStyle |= 1
    fb.save(datei)


