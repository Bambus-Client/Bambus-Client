# ------------------------------------------------------------------ Akzente (zusammengesetzt)
AKZENTE = {
    'grave': ["#.", ".#"], 'acute': [".#", "#."], 'circ': [".#.", "#.#"],
    'tilde': [".#.#", "#.#."], 'uml': ["#.#"], 'ring': [".#.", "#.#", ".#."],
}


def mit_akzent(ch, basis, akzent):
    zeilen, unten = G[basis]
    a = AKZENTE[akzent]
    b = max(len(zeilen[0]), len(a[0]))
    def mitte(r):
        links = (b - len(r)) // 2
        return "." * links + r + "." * (b - len(r) - links)
    z(ch, [mitte(r) for r in a] + ["." * b] + [mitte(r) for r in zeilen], unten)


